# Page-range corrections
PAGE_RANGE_FIXES = {
    13: {"end_page": 182},  # was 177
    14: {"start_page": 183, "end_page": 189},  # was 178-189
    15: {"end_page": 205},  # was 200
}

# OCR corrections for topics
TOPIC_OCR_FIXES = {
    3: {
        "গ্রহ-কুমার ও গ্রহাণু পুঞ্জ": "গ্রহসমূহ ও গ্রহাণু পুঞ্জ",
    },
}

def main():
    with open(TOPIC_MAP_PATH, 'r', encoding='utf-8') as f:
        topic_map = json.load(f)
    
    for entry in topic_map:
        ch = entry["chapter_no"]
        
        # Fix learning_outcomes
        if ch in REAL_SHIKHONFOL:
            entry["learning_outcomes"] = REAL_SHIKHONFOL[ch]
        
        # Fix page ranges
        if ch in PAGE_RANGE_FIXES:
            for key, val in PAGE_RANGE_FIXES[ch].items():
                entry[key] = val
        
        # Fix OCR errors in topics
        if ch in TOPIC_OCR_FIXES:
            new_topics = []
            for topic in entry["topics"]:
                if topic in TOPIC_OCR_FIXES[ch]:
                    topic = TOPIC_OCR_FIXES[ch][topic]
                new_topics.append(topic)
            entry["topics"] = new_topics
    
    with open(TOPIC_MAP_PATH, 'w', encoding='utf-8') as f:
        json.dump(topic_map, f, ensure_ascii=False, indent=2)
    
    print(f"Fixed {len(topic_map)} chapters")
    for entry in topic_map:
        ch = entry["chapter_no"]
        outcomes_count = len(entry["learning_outcomes"])
        topics_count = len(entry["topics"])
        print(f"  Ch{ch:2d}: {outcomes_count} outcomes, {topics_count} topics, pages {entry['source_pages']}")

if __name__ == "__main__":
    main()
